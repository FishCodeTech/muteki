"""Generate TypeScript compatibility contracts from this repository's JSON schemas.

The JSON files in apps/frontend/lib/contracts are the checked-in source. They
track migrated Rust APIs where possible and label legacy Python compatibility
metadata explicitly. This is not an exhaustive OpenAPI description of Rust.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1] / "apps/frontend/lib/contracts"
SCHEMA = ROOT / "schema.json"
OPENAPI = ROOT / "openapi.json"
ORDER = ROOT / "order.json"


def ts_type(node: Any, namespace: str = "") -> str:
    if not isinstance(node, dict) or not node:
        return "unknown"
    if "$ref" in node:
        return namespace + str(node["$ref"]).rsplit("/", 1)[-1]
    for key in ("anyOf", "oneOf"):
        if key in node:
            return " | ".join(dict.fromkeys(ts_type(part, namespace) for part in node[key]))
    if "allOf" in node:
        return " & ".join(dict.fromkeys(ts_type(part, namespace) for part in node["allOf"]))
    if "enum" in node:
        return " | ".join(json.dumps(value, ensure_ascii=False) for value in node["enum"])
    if "const" in node:
        return json.dumps(node["const"], ensure_ascii=False)
    kind = node.get("type")
    if isinstance(kind, list):
        return " | ".join(ts_type({**node, "type": part}, namespace) for part in kind)
    if kind == "string":
        return "string"
    if kind in ("integer", "number"):
        return "number"
    if kind == "boolean":
        return "boolean"
    if kind == "null":
        return "null"
    if kind == "array":
        return f"{ts_type(node.get('items'), namespace)}[]"
    if kind == "object" or "properties" in node:
        return ts_object(node, namespace)
    return "unknown"


def ts_object(node: dict[str, Any], namespace: str = "", order: list[str] | None = None) -> str:
    properties = node.get("properties") or {}
    if not properties:
        return "Record<string, unknown>"
    required = set(node.get("required") or [])
    names = [name for name in (order or []) if name in properties]
    names.extend(name for name in properties if name not in names)
    fields = [f"  {name}{'' if name in required else '?'}: {ts_type(properties[name], namespace)};"
              for name in names]
    return "{\n" + "\n".join(fields) + "\n}"


def render_models(schema: dict[str, Any], order: dict[str, Any]) -> str:
    version = int(schema.get("x-muteki-contracts-schema-version", 2))
    lines = ["// Generated by scripts/generate_frontend_contracts.py from local schema.json. DO NOT EDIT.",
             "// Compatibility schema; see schema.json for legacy metadata boundaries.",
             f"export const CONTRACTS_SCHEMA_VERSION = {version};", ""]
    names = [name for name in order["definitions"] if name in schema["$defs"]]
    names.extend(name for name in schema["$defs"] if name not in names)
    for name in names:
        definition = schema["$defs"][name]
        description = str(definition.get("description") or "").splitlines()[:1]
        description = description[0].strip() if description else ""
        if description:
            lines.append(f"/** {description.replace('``', '')} */")
        if definition.get("enum"):
            lines.append(f"export type {name} = {ts_type(definition)};")
        else:
            lines.append(f"export interface {name} {ts_object(definition, order=order['properties'].get(name))}")
        lines.append("")
    return "\n".join(lines)


def safe_name(value: str) -> str:
    result = "".join(char if char.isalnum() else "_" for char in value)
    return ("_" if result and result[0].isdigit() else "") + (result or "Anonymous")


def api_ts_type(schema: Any) -> str:
    if not isinstance(schema, dict) or not schema:
        return "unknown"
    if "$ref" in schema:
        return "OpenApiSchemas." + safe_name(str(schema["$ref"]).rsplit("/", 1)[-1])
    for key in ("anyOf", "oneOf"):
        if key in schema:
            return " | ".join(dict.fromkeys(api_ts_type(item) for item in schema[key]))
    if "allOf" in schema:
        return " & ".join(dict.fromkeys(api_ts_type(item) for item in schema["allOf"]))
    if "enum" in schema:
        return " | ".join(json.dumps(item, ensure_ascii=False) for item in schema["enum"])
    if "const" in schema:
        return json.dumps(schema["const"], ensure_ascii=False)
    kind = schema.get("type")
    if isinstance(kind, list):
        return " | ".join(api_ts_type({**schema, "type": item}) for item in kind)
    if kind == "string":
        return "string"
    if kind in ("number", "integer"):
        return "number"
    if kind == "boolean":
        return "boolean"
    if kind == "null":
        return "null"
    if kind == "array":
        return f"Array<{api_ts_type(schema.get('items'))}>"
    if kind == "object" or "properties" in schema:
        required = set(schema.get("required") or [])
        fields = [f"{json.dumps(name, ensure_ascii=False)}{'' if name in required else '?'}: {api_ts_type(field)}"
                  for name, field in sorted((schema.get("properties") or {}).items())]
        if schema.get("additionalProperties"):
            fields.append("[key: string]: unknown")
        return "{ " + "; ".join(fields) + " }"
    return "unknown"


def parameters(operation: dict[str, Any], location: str) -> str:
    fields = []
    for parameter in operation.get("parameters") or []:
        if parameter.get("in") != location:
            continue
        name = str(parameter.get("name") or "value")
        fields.append(f"{json.dumps(name, ensure_ascii=False)}{'' if parameter.get('required') else '?'}: "
                      f"{api_ts_type(parameter.get('schema'))}")
    return "{ " + "; ".join(fields) + " }"


def body_type(operation: dict[str, Any]) -> str:
    content = (operation.get("requestBody") or {}).get("content") or {}
    for media in ("application/json", "multipart/form-data"):
        if media in content:
            return api_ts_type(content[media].get("schema"))
    return api_ts_type(next(iter(content.values())).get("schema")) if content else "never"


def response_type(operation: dict[str, Any]) -> str:
    variants = []
    for response in (operation.get("responses") or {}).values():
        content = response.get("content") or {}
        if "application/json" in content:
            value = api_ts_type(content["application/json"].get("schema"))
            if value not in variants:
                variants.append(value)
    return " | ".join(variants) if variants else "unknown"


def render_openapi(schema: dict[str, Any]) -> str:
    lines = ["// Generated by scripts/generate_frontend_contracts.py from local openapi.json. DO NOT EDIT.",
             "// Compatibility snapshot; not an exhaustive description of the Rust service.",
             "", "export namespace OpenApiSchemas {"]
    for name, body in sorted(((schema.get("components") or {}).get("schemas") or {}).items()):
        lines.append(f"  export type {safe_name(name)} = {api_ts_type(body)};")
    lines.extend(["}", "", "export interface OpenApiOperations {"])
    methods = {"get", "post", "put", "patch", "delete", "options", "head"}
    for path, item in sorted((schema.get("paths") or {}).items()):
        for method, operation in sorted(item.items()):
            if method not in methods or not isinstance(operation, dict):
                continue
            operation_id = str(operation.get("operationId") or f"{method}_{path}")
            lines.extend([f"  {json.dumps(operation_id)}: {{",
                          f"    method: {json.dumps(method.upper())};",
                          f"    path: {json.dumps(path)};",
                          f"    pathParams: {parameters(operation, 'path')};",
                          f"    query: {parameters(operation, 'query')};",
                          f"    body: {body_type(operation)};",
                          f"    response: {response_type(operation)};", "  };"])
    lines.extend(["}", "", "export type OpenApiOperationId = keyof OpenApiOperations;",
                  "export type OpenApiOperation<K extends OpenApiOperationId> = OpenApiOperations[K];", ""])
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    model_schema = json.loads(SCHEMA.read_text())
    order = json.loads(ORDER.read_text())
    api_schema = json.loads(OPENAPI.read_text())
    outputs = {ROOT / "index.ts": render_models(model_schema, order),
               ROOT / "openapi.ts": render_openapi(api_schema)}
    stale = [path for path, content in outputs.items() if not path.exists() or path.read_text() != content]
    if args.check:
        if stale:
            print("stale generated contracts:", *(str(path) for path in stale), sep="\n  ")
            return 1
        print("frontend contracts are current")
        return 0
    for path, content in outputs.items():
        path.write_text(content)
        print(f"wrote {path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
