export const TIMELINE_COPY = { zh, en } as const;
export type TimelineLang = keyof typeof TIMELINE_COPY;

export interface TimelineEnv {
  copy: TimelineCopy;
  lang: TimelineLang;
  /** Epoch ms of trace time 0, for absolute timestamps in tooltips. */
  origin: number | null;
  /** Compressed idle stretches; displayed times convert through them. */
  gaps: readonly TimeGap[];
}

export const TimelineEnvContext = createContext<TimelineEnv>({ copy: zh, lang: "zh", origin: null, gaps: [] });

export const useTimelineEnv = () => useContext(TimelineEnvContext);
export const useCopy = () => useContext(TimelineEnvContext).copy;
